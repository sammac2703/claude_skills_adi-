#!/usr/bin/env python3
"""
Read a corporate template (.potx or .pptx) and write a theme JSON the deck
builder can use, plus a short report of what it found.

    python extract_template.py "ADI Template.potx" -o themes/adi.json

It pulls: slide size, theme colours (dk1/lt1/dk2/lt2/accent1-6), heading and
body fonts, layout names with their placeholders, any footer / legal text on
the master or layouts, and whether the master carries a logo picture.

Review the JSON afterwards: the mapping from theme colours to roles
(dark_bg, accent, ramp_start ...) is a best guess and needs a human eye.
Keep the template and the generated theme out of public repos; see README.
"""
from __future__ import annotations

import argparse
import json
import sys
import zipfile
from pathlib import Path

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parent))
from deckkit import DEFAULT_THEME, EMU_PER_IN, deep_merge, luminance, open_template  # noqa: E402

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"


def theme_xml(path: Path):
    with zipfile.ZipFile(path) as z:
        names = sorted(n for n in z.namelist() if n.startswith("ppt/theme/theme") and n.endswith(".xml"))
        return etree.fromstring(z.read(names[0])) if names else None


def scheme_colours(root):
    out = {}
    cs = root.find(f".//{A}clrScheme")
    if cs is None:
        return out
    for child in cs:
        tag = child.tag.replace(A, "")
        c = child[0]
        out[tag] = c.get("val") if c.tag == f"{A}srgbClr" else c.get("lastClr", "000000")
    return out


def scheme_fonts(root):
    fs = root.find(f".//{A}fontScheme")
    if fs is None:
        return None, None
    maj = fs.find(f"{A}majorFont/{A}latin")
    mnr = fs.find(f"{A}minorFont/{A}latin")
    return (maj.get("typeface") if maj is not None else None,
            mnr.get("typeface") if mnr is not None else None)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("template")
    ap.add_argument("-o", "--out", default=None)
    a = ap.parse_args()
    src = Path(a.template).resolve()
    root = theme_xml(src)
    cols = scheme_colours(root) if root is not None else {}
    head, body = scheme_fonts(root) if root is not None else (None, None)
    prs = open_template(str(src))

    rep = [f"# Template report: {src.name}", ""]
    rep.append(f"Slide size: {prs.slide_width/EMU_PER_IN:.3f} x {prs.slide_height/EMU_PER_IN:.3f} in")
    rep.append(f"Fonts: heading = {head}, body = {body}")
    rep.append("Theme colours: " + ", ".join(f"{k} #{v}" for k, v in cols.items()))
    rep += ["", "## Layouts"]
    footer_texts, logo = set(), False
    for m_i, master in enumerate(prs.slide_masters):
        for sh in master.shapes:
            if sh.shape_type == 13:
                logo = True
            if sh.has_text_frame and sh.text_frame.text.strip() and not sh.is_placeholder:
                footer_texts.add(sh.text_frame.text.strip())
        for lay in master.slide_layouts:
            phs = ", ".join(f"{p.placeholder_format.type}".split(".")[-1].split(" ")[0] + f"#{p.placeholder_format.idx}"
                            for p in lay.placeholders)
            rep.append(f"- master {m_i} / **{lay.name}**: {phs or 'no placeholders'}")
            for sh in lay.shapes:
                if sh.has_text_frame and sh.text_frame.text.strip() and not sh.is_placeholder:
                    footer_texts.add(sh.text_frame.text.strip())
                if sh.shape_type == 13:
                    logo = True
    rep += ["", "## Fixed text on master/layouts (legal, confidentiality, footers)"]
    rep += [f"- {t}" for t in sorted(footer_texts)] or ["- none found"]
    rep.append("")
    rep.append(f"Logo picture on master/layout: {'yes' if logo else 'no'}")

    # Best-guess role mapping
    dk = [cols.get(k) for k in ("dk1", "dk2") if cols.get(k)]
    lt = [cols.get(k) for k in ("lt1", "lt2") if cols.get(k)]
    acc = [cols.get(f"accent{i}") for i in range(1, 7) if cols.get(f"accent{i}")]
    darkest = min(dk + acc, key=luminance) if (dk or acc) else DEFAULT_THEME["colors"]["dark_bg"]
    lightest_acc = max(acc, key=luminance) if acc else DEFAULT_THEME["colors"]["ramp_end"]
    colors = {
        "dark_bg": darkest, "dark_bg2": "000000",
        "light_bg": lt[0] if lt else "FFFFFF", "light_bg2": lt[1] if len(lt) > 1 else "F2F2F2",
        "on_light": dk[0] if dk else "1A1A1A",
        "accent": acc[0] if acc else DEFAULT_THEME["colors"]["accent"],
        "accent2": acc[1] if len(acc) > 1 else DEFAULT_THEME["colors"]["accent2"],
        "ours": acc[0] if acc else DEFAULT_THEME["colors"]["ours"],
        "ramp_start": darkest, "ramp_end": lightest_acc,
    }
    theme = deep_merge(DEFAULT_THEME, {
        "name": src.stem,
        "_note": "Generated by extract_template.py. Check the colour-role mapping and fonts by eye.",
        "template": str(src),
        "mode": "template" if logo or footer_texts else "dark",
        "fonts": {
            "heavy": {"face": head or "Arial", "bold": True},
            "head": {"face": head or "Arial", "bold": True},
            "body": {"face": body or "Calibri", "bold": False},
            "light": {"face": body or "Calibri", "bold": False},
        },
        "colors": colors,
        "footer": {"text": None if footer_texts else DEFAULT_THEME["footer"]["text"],
                   "required_text": sorted(footer_texts, key=len)[0] if footer_texts else None,
                   "slide_numbers": not bool(footer_texts)},
        "theme_scheme": cols,
    })
    rep += ["", "## Suggested next steps",
            "- If the template has a light weight of its font family (e.g. 'X Light'), set fonts.light to it.",
            "- mode 'template' keeps the master's backgrounds, logo and footers; use 'dark' or 'light' to let the builder paint backgrounds while still using the template's masters.",
            "- Set footer.required_text to the exact legal string so lint enforces it."]
    out = Path(a.out or src.with_suffix(".theme.json"))
    out.write_text(json.dumps(theme, indent=2, ensure_ascii=False), encoding="utf-8")
    report = "\n".join(rep) + "\n"
    out.with_suffix(".report.md").write_text(report, encoding="utf-8")
    print(report)
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
